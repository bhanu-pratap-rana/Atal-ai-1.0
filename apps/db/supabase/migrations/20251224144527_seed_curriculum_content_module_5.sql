-- Topic 17.2: UPI Payments
('M5', 'T17.2', 'en', 'curriculum', 'UPI Payments - Send Money Instantly

Learning Objective: Set up and use UPI for safe digital transactions.

What is UPI?
Unified Payments Interface - connects your bank account to payment apps. Transfer money using phone number, UPI ID, or QR code.

Setting Up UPI:
1. Download UPI app (Google Pay, PhonePe, BHIM)
2. Register with phone number (linked to bank)
3. Select your bank
4. Verify with debit card details
5. Set UPI PIN (4 or 6 digits)
6. Create UPI ID (yourname@upi)

Ways to Pay:
1. UPI ID: Enter receiver UPI ID (example: shopname@paytm)
2. Phone Number: Send to registered mobile number
3. QR Code: Scan and pay (most common at shops)
4. Bank Account: Enter account number and IFSC

Making a Payment:
1. Open UPI app
2. Select payment method (QR/Phone/UPI ID)
3. Enter amount
4. Add note (optional but helpful)
5. Enter UPI PIN
6. Payment complete!

Transaction Limits:
- Per transaction: Up to Rs 1 lakh
- Daily limit: Varies by bank (usually Rs 1-2 lakh)
- No charges for basic UPI transfers

Safety Tips:
- Never share UPI PIN with anyone
- Verify receiver details before paying
- Check amount carefully
- Do not scan unknown QR codes
- Keep UPI PIN different from other passwords

If Payment Fails:
- Money usually returns in 24-48 hours
- Check transaction history in app
- Contact bank if not refunded in 5 days
- Note the UTR number for complaints

Common Scam: Someone sends you a collect request pretending to send money. NEVER approve unknown collect requests!', '{"duration_minutes": 25, "has_video": false}'),

